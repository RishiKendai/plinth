// Command worker runs background jobs: purge expired sessions (Phase 1) and generate recurring occurrences (Phase 3).
// Jobs must be safe to retry (CLAUDE.md section 12).
package main

import (
	"context"
	"fmt"
	"os"
	"os/signal"
	"syscall"
	"time"

	"plinth/server/internal/analytics"
	"plinth/server/internal/attachments"
	"plinth/server/internal/auth"
	"plinth/server/internal/platform/config"
	"plinth/server/internal/platform/database"
	"plinth/server/internal/platform/logging"
	"plinth/server/internal/platform/security"
	"plinth/server/internal/platform/storage"
	"plinth/server/internal/recurrence"
	"plinth/server/internal/settings"
	"plinth/server/internal/users"
)

var version = "dev"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "worker:", err)
		os.Exit(1)
	}
}

func run() error {
	cfg, err := config.Load()
	if err != nil {
		return fmt.Errorf("configuration: %w", err)
	}
	log := logging.New(os.Stdout, cfg.LogLevel, cfg.IsProduction())
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	db, err := database.Connect(ctx, cfg)
	if err != nil {
		return err
	}
	defer db.Close()
	svc := auth.NewService(auth.NewStore(db), security.DefaultHasher(), auth.Config{Pepper: cfg.TokenPepper}, log)

	purge := func() {
		jctx, cancel := context.WithTimeout(ctx, time.Minute)
		defer cancel()
		s, err := svc.Purge(jctx)
		if err != nil {
			log.Error("purge failed", "err", err.Error())
			return
		}
		log.Info("purge done", "sessions", s)
	}
	// Generation needs only the database: it creates expectations, never transactions.
	rec := recurrence.NewService(db, nil, nil)
	generate := func() {
		jctx, cancel := context.WithTimeout(ctx, 5*time.Minute)
		defer cancel()
		n, err := rec.GenerateAll(jctx, 50)
		if err != nil {
			log.Error("occurrence generation failed", "err", err.Error(), "created_before_failure", n)
			return
		}
		log.Info("occurrence generation done", "created", n)
	}
	var store storage.Store
	if cfg.R2.Configured() {
		if s3, err := storage.NewS3(cfg.R2.Endpoint, cfg.R2.Bucket, cfg.R2.AccessKeyID, cfg.R2.SecretAccessKey); err == nil {
			store = s3
		}
	}
	att := attachments.NewService(db, store)
	cleanup := func() {
		jctx, cancel := context.WithTimeout(ctx, 2*time.Minute)
		defer cancel()
		n, err := att.Cleanup(jctx, 100)
		if err != nil {
			log.Error("attachment cleanup failed", "err", err.Error())
			return
		}
		log.Info("attachment cleanup done", "removed", n)
	}
	ana := analytics.NewService(db, settings.NewService(db))
	// Reports are normally generated by the API right after they are requested; this sweep picks up anything a restart missed.
	reports := func() {
		jctx, cancel := context.WithTimeout(ctx, 5*time.Minute)
		defer cancel()
		if n, err := ana.ProcessQueued(jctx, 20, log); err != nil {
			log.Error("report sweep failed", "err", err.Error())
		} else if n > 0 {
			log.Info("reports generated", "count", n)
		}
	}
	purger := users.NewPurger(db, objectStore(store), log)
	eraseDue := func() {
		jctx, cancel := context.WithTimeout(ctx, 10*time.Minute)
		defer cancel()
		if n, err := purger.PurgeDue(jctx, cfg.AccountDeletionGrace, 20); err != nil {
			log.Error("account purge sweep failed", "err", err.Error())
		} else if n > 0 {
			log.Info("accounts erased", "count", n)
		}
	}
	log.Info("worker started", "version", version)
	generate()
	cleanup()
	reports()
	eraseDue()
	tick := time.NewTicker(time.Hour)
	defer tick.Stop()
	fast := time.NewTicker(time.Minute)
	defer fast.Stop()
	for {
		select {
		case <-ctx.Done():
			log.Info("worker stopped")
			return nil
		case <-fast.C:
			reports()
		case <-tick.C:
			purge()
			eraseDue()
			generate()
			cleanup()
		}
	}
}

// objectStore turns a possibly-nil storage.Store into an interface that is truly nil when R2 is not configured.
func objectStore(s storage.Store) users.ObjectStore {
	if s == nil {
		return nil
	}
	return s
}
